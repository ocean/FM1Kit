#!/usr/bin/env python3
"""Builds m-bootloader's flash loaders and their notice into FM1Rescue's code.

Reads Sources/FM1Rescue/Resources/ and writes Sources/FM1Rescue/FlashLoaderImage+Embedded.swift,
so fm1probe needs no resource bundle beside it. Run it after replacing the loaders or NOTICE.md;
FM1RescueTests checks the result matches them.
"""
import base64
import hashlib
import pathlib
import textwrap

root = pathlib.Path(__file__).resolve().parent.parent
resources = root / "Sources/FM1Rescue/Resources"
output = root / "Sources/FM1Rescue/FlashLoaderImage+Embedded.swift"


def embedded(name: str, swift_name: str) -> str:
    """A Swift property holding the file's bytes in base64, under its SHA-256."""
    data = (resources / name).read_bytes()
    lines = textwrap.wrap(base64.b64encode(data).decode(), 96)
    body = "\n".join(f"        {line}" for line in lines)
    digest = hashlib.sha256(data).hexdigest()
    return (
        f"    /// `{name}`, SHA-256 {digest[:16]}….\n"
        f'    static let {swift_name} = """\n{body}\n        """\n'
    )


notice = (resources / "NOTICE.md").read_text().rstrip("\n")
notice_body = "\n".join(f"        {line}" if line else "" for line in notice.split("\n"))
swift = f'''// Generated by scripts/embed-flash-loaders.py from Resources/; don't edit it by hand.
#if os(macOS)
/// m-bootloader's flash loader builds, built into FM1Rescue.
extension FlashLoaderImage {{
{embedded("mflr-loader-a.bin", "loaderABase64")}
{embedded("mflr-loader-b.bin", "loaderBBase64")}}}

/// The notices for code and files FM1Kit takes from others, which `fm1probe licences` prints.
public enum ThirdPartyNotices {{
    /// `Resources/NOTICE.md`: m-bootloader's flash loader and M-Flasher's code (MIT).
    public static let text = #"""
{notice_body}
        """#
}}
#endif
'''
output.write_text(swift)
print(f"Wrote {output.relative_to(root)}")
